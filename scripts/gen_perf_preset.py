#!/usr/bin/env python3
"""
gen_perf_preset.py — emit a performance-tuned server.toml for HorizonR-Mobile builds.

Produces three preset files in the given output directory:
  server-perf-light.toml   — small VPS / low-RAM device (<=4 cores, 1-2 GB RAM)
  server-perf-mid.toml     — mid VPS / 4-core 4 GB RAM, 10-25 players
  server-perf-high.toml    — 8-core 8+ GB RAM, 25-50 players

Usage:
  python3 scripts/gen_perf_preset.py [output_dir]
  output_dir defaults to dist/server-presets/

No runtime dependencies beyond the standard library.
Free, no reverse engineering, no paid services.

What each knob does (all are plain server.toml keys — no patches, no mods):
  view_distance          — chunks *sent* to the client (visual range)
  simulation_distance    — chunks where mobs, crops and redstone actually *tick*
                           Reducing this is the biggest tick-time lever.
  max_view_distance      — Horizon-only: render already-saved chunks beyond view_distance
                           without ticking them; the server pulls in automatically when
                           ticks go over 50 ms, so it is a free backpressure mechanism.
  low_memory             — disables transparent huge pages (~190 MB saved at 20 players,
                           +1.2 % tick time — good for constrained hosts).
  restart_on_crash       — keep the server alive automatically; free "reliability" win.

Pregen note (printed in each preset's header comment):
  Run `horizon-server cmd pregen start 2500` once after first start to pre-generate a
  2500-chunk radius around spawn.  This eliminates chunk-generation spikes during
  gameplay.  Requires `horizon-pregen = true` under [properties] in server.toml.
"""

import os
import sys
import textwrap

OUTPUT_DIR = sys.argv[1] if len(sys.argv) > 1 else "dist/server-presets"

HEADER = """\
# HorizonR performance preset — generated by scripts/gen_perf_preset.py
# Drop this file next to the horizon-server binary and rename it server.toml,
# or merge the values you want into your existing server.toml.
#
# PREGEN TIP (do this once after first start):
#   Add `horizon-pregen = true` under [properties], start the server, then run:
#     horizon-server cmd pregen start 2500
#   This pre-generates a 2500-chunk radius around spawn and eliminates the
#   chunk-gen lag spikes players feel when exploring new terrain.
#
# RELAY TIP (free, no reverse engineering):
#   Build and run `horizon-relay` from the repo on any free-tier VPS, Raspberry Pi,
#   or Oracle Free Tier ARM instance.  One open TCP port (default 7000) is enough.
#   Add the relay address to [friends] in server.toml so invite codes include it
#   automatically:
#     [friends]
#     relay = "your-host-or-ip:7000"
"""

PRESETS = {
    "light": {
        "desc": "light — small VPS, Raspberry Pi, or low-RAM device (<=4 cores, 1-2 GB RAM, ≤10 players)",
        "view_distance": 6,
        "simulation_distance": 5,
        "max_view_distance": 10,
        "low_memory": "true",
        "max_players": 10,
        "extra_properties": {
            # vanilla server.properties pass-throughs for extra headroom
            "entity-broadcast-range-percentage": "50",
        },
    },
    "mid": {
        "desc": "mid — 4-core VPS, 4 GB RAM, 10-25 players",
        "view_distance": 8,
        "simulation_distance": 6,
        "max_view_distance": 12,
        "low_memory": "false",
        "max_players": 25,
        "extra_properties": {
            "entity-broadcast-range-percentage": "75",
        },
    },
    "high": {
        "desc": "high — 8-core host, 8+ GB RAM, 25-50 players",
        "view_distance": 10,
        "simulation_distance": 8,
        "max_view_distance": 16,
        "low_memory": "false",
        "max_players": 50,
        "extra_properties": {},
    },
}


def render_preset(name: str, p: dict) -> str:
    extra_props = ""
    if p["extra_properties"]:
        pairs = "\n".join(
            f'{k} = "{v}"' for k, v in p["extra_properties"].items()
        )
        extra_props = f"\n# Extra server.properties pass-throughs\n{pairs}\n"

    body = f"""{HEADER}
# Preset: {p['desc']}

motd = "A Minecraft Server"
port = 25565
max_players = {p['max_players']}
online_mode = true
whitelist = true
view_distance = {p['view_distance']}         # chunks sent to the client
simulation_distance = {p['simulation_distance']}     # chunks where mobs/crops/redstone tick
max_view_distance = {p['max_view_distance']}       # Horizon: show saved chunks beyond view_distance without ticking them

[world]
name = "world"
game_mode = "survival"
difficulty = "normal"

[engine]
restart_on_crash = true
low_memory = {p['low_memory']}        # true: ~190 MB less RAM, ~+1 % tick time

[properties]
# Uncomment to enable world pregeneration (run once after first start):
# horizon-pregen = true
{extra_props}
[backups]
every = "6h"
keep = 12
"""
    return body


def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    for name, preset in PRESETS.items():
        path = os.path.join(OUTPUT_DIR, f"server-perf-{name}.toml")
        content = render_preset(name, preset)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"wrote {path}")
    print(f"\n{len(PRESETS)} preset(s) written to {OUTPUT_DIR}/")


if __name__ == "__main__":
    main()
